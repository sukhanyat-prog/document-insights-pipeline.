-- One-time Snowflake setup. Run as ACCOUNTADMIN (or a role that can create these objects).
-- Replace the names to match your .env. Review each statement against your account's edition and region.

USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS PIPELINE_ROLE;
CREATE DATABASE IF NOT EXISTS PIPELINE_DB;
CREATE SCHEMA IF NOT EXISTS PIPELINE_DB.PIPELINE_TEMPLATE;
CREATE WAREHOUSE IF NOT EXISTS PIPELINE_WH WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE;

GRANT USAGE ON DATABASE PIPELINE_DB TO ROLE PIPELINE_ROLE;
GRANT ALL ON SCHEMA PIPELINE_DB.PIPELINE_TEMPLATE TO ROLE PIPELINE_ROLE;
GRANT USAGE, OPERATE ON WAREHOUSE PIPELINE_WH TO ROLE PIPELINE_ROLE;

-- Cortex LLM functions (document text is processed inside Snowflake)
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE PIPELINE_ROLE;

-- Give your user (local development) and, below, the container service this role
-- GRANT ROLE PIPELINE_ROLE TO USER <your_user>;

-- Tables and the stage are created by:  python scripts/run_pipeline.py setup

-- ---- Snowpark Container Services (hosting the Flask dashboard) ----
CREATE COMPUTE POOL IF NOT EXISTS PIPELINE_POOL
  MIN_NODES = 1 MAX_NODES = 1 INSTANCE_FAMILY = CPU_X64_XS;
CREATE IMAGE REPOSITORY IF NOT EXISTS PIPELINE_DB.PIPELINE_TEMPLATE.IMAGES;

GRANT USAGE, MONITOR ON COMPUTE POOL PIPELINE_POOL TO ROLE PIPELINE_ROLE;
GRANT READ, WRITE ON IMAGE REPOSITORY PIPELINE_DB.PIPELINE_TEMPLATE.IMAGES TO ROLE PIPELINE_ROLE;
GRANT BIND SERVICE ENDPOINT ON ACCOUNT TO ROLE PIPELINE_ROLE;

-- Flask session / CSRF key. Generate one:  python -c "import secrets; print(secrets.token_hex(32))"
USE ROLE PIPELINE_ROLE;
CREATE SECRET IF NOT EXISTS PIPELINE_DB.PIPELINE_TEMPLATE.APP_SECRET_KEY
  TYPE = GENERIC_STRING SECRET_STRING = '<paste-the-generated-key>';
